/**
 * Loveneet Suite — Reliable Cross-Platform File Delivery Service
 * Manages downloading and saving generated presentations for both Web and Windows Desktop environments.
 * Implements Phase 5 pre-download validation and post-save SHA-256 disk re-read verification.
 * 
 * NOTE: Structural OpenXML validation only; not proof of Microsoft PowerPoint application compatibility.
 */

import { isDesktop } from "./platform.ts";
import { validatePptx, type PptxValidationResult, type ExpectedPresentationDetails } from "./pptxValidator.ts";

export interface DeliveryResult {
  success: boolean;
  platform: "desktop" | "web";
  savedPath?: string;
  byteSize: number;
  sha256?: string;
  validation?: PptxValidationResult;
  error?: string;
}

/**
 * Converts a Blob to a base64 encoded string.
 */
export async function blobToBase64(blob: Blob): Promise<string> {
  const arrayBuffer = await blob.arrayBuffer();
  let binary = "";
  const bytes = new Uint8Array(arrayBuffer);
  const len = bytes.byteLength;
  for (let i = 0; i < len; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary);
}

/**
 * Delivers a validated presentation Blob to the user.
 * Runs structural pre-delivery validation (Checks 1-10) before download/save.
 * On Windows Desktop, performs atomic save and Check 11 (re-read from disk and SHA-256 match).
 * On any failure, download/save is blocked and an actionable error is returned.
 */
export async function deliverPresentation(
  blob: Blob,
  defaultFilename: string,
  promptDesktopDialog: boolean = false,
  expected?: ExpectedPresentationDetails
): Promise<DeliveryResult> {
  const cleanFilename = defaultFilename.trim().replace(/[/\\?%*:|"<>]/g, "_");
  const byteSize = blob.size;

  // Pre-Download Structural Validation (Checks 1-10)
  const validation = await validatePptx(blob, expected);
  if (!validation.valid) {
    const errorMsg = `Pre-download structural validation failed (${validation.errors.length} check(s) failed):\n• ` + validation.errors.join("\n• ");
    return {
      success: false,
      platform: isDesktop() ? "desktop" : "web",
      byteSize,
      sha256: validation.sha256,
      validation,
      error: errorMsg
    };
  }

  // Windows Desktop Save Path
  if (isDesktop() && window.electronAPI) {
    try {
      let targetPath = "";

      if (promptDesktopDialog && window.electronAPI.dialog?.showSaveDialog) {
        const dialogRes = await window.electronAPI.dialog.showSaveDialog({
          title: "Save PowerPoint Catalogue Presentation",
          defaultPath: cleanFilename,
          filters: [
            { name: "PowerPoint Presentation (*.pptx)", extensions: ["pptx"] },
            { name: "All Files", extensions: ["*"] }
          ]
        });

        if (dialogRes.canceled || !dialogRes.filePath) {
          return {
            success: false,
            platform: "desktop",
            byteSize,
            sha256: validation.sha256,
            validation,
            error: "File save was cancelled by the user."
          };
        }
        targetPath = dialogRes.filePath;
      }

      if (!targetPath && window.electronAPI.fs?.writeFile) {
        targetPath = cleanFilename;
      }

      if (targetPath && window.electronAPI.fs?.writeFile) {
        const b64 = await blobToBase64(blob);
        const writeRes = await window.electronAPI.fs.writeFile(targetPath, b64);

        if (!writeRes.success) {
          throw new Error(writeRes.error || "Failed to write file to disk.");
        }

        const resolvedPath = writeRes.path || targetPath;

        // Post-write existence check
        const exists = await window.electronAPI.fs.exists(resolvedPath);
        if (!exists) {
          throw new Error("File verification failed: Output file not found on disk after write.");
        }

        // Check 11: Re-read file from disk and compare SHA-256 with generated bytes
        let diskSha256 = writeRes.sha256;
        if (window.electronAPI.fs.readFile) {
          const diskRead = await window.electronAPI.fs.readFile(resolvedPath);
          if (!diskRead.success || !diskRead.sha256) {
            throw new Error(`Check 11 Failed: Could not re-read saved file from disk for verification: ${diskRead.error || "Read error"}`);
          }
          diskSha256 = diskRead.sha256;
        }

        if (diskSha256 && diskSha256 !== validation.sha256) {
          throw new Error(`Check 11 Failed: Post-save disk SHA-256 hash mismatch! In-memory=${validation.sha256}, On-disk=${diskSha256}. Delivery aborted.`);
        }

        return {
          success: true,
          platform: "desktop",
          savedPath: resolvedPath,
          byteSize: writeRes.size || byteSize,
          sha256: diskSha256 || validation.sha256,
          validation
        };
      }
    } catch (desktopErr: any) {
      return {
        success: false,
        platform: "desktop",
        byteSize,
        sha256: validation.sha256,
        validation,
        error: `Desktop file save failed: ${desktopErr.message || String(desktopErr)}`
      };
    }
  }

  // Web Browser Download Path
  try {
    const pptxBlob = new Blob([await blob.arrayBuffer()], {
      type: "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    });

    if (typeof document !== "undefined" && typeof URL.createObjectURL === "function") {
      const url = URL.createObjectURL(pptxBlob);
      const link = document.createElement("a");
      link.href = url;
      link.download = cleanFilename;
      link.style.display = "none";
      document.body.appendChild(link);
      link.click();
      link.remove();

      if (typeof window !== "undefined" && window.setTimeout) {
        window.setTimeout(() => {
          try {
            URL.revokeObjectURL(url);
          } catch {}
        }, 3000);
      }
    }

    return {
      success: true,
      platform: "web",
      byteSize,
      sha256: validation.sha256,
      validation
    };
  } catch (webErr: any) {
    return {
      success: false,
      platform: "web",
      byteSize,
      sha256: validation.sha256,
      validation,
      error: `Browser download failed: ${webErr.message || String(webErr)}`
    };
  }
}

/**
 * Opens the saved presentation with default registered application (e.g. Microsoft PowerPoint).
 */
export async function openPresentationInApp(filePath: string): Promise<{ success: boolean; error?: string }> {
  if (isDesktop() && window.electronAPI?.fs?.openPath) {
    return await window.electronAPI.fs.openPath(filePath);
  }
  return { success: false, error: "Not supported in browser environment." };
}

/**
 * Reveals the saved file in Windows File Explorer.
 */
export async function revealPresentationInFolder(filePath: string): Promise<boolean> {
  if (isDesktop() && window.electronAPI?.fs?.showItemInFolder) {
    return await window.electronAPI.fs.showItemInFolder(filePath);
  }
  return false;
}
